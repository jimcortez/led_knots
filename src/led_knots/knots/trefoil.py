"""
Trefoil knot creation using CadQuery.

Creates a trefoil knot by sweeping an LED circle cross-section
along a mathematical trefoil knot path generated by pyknotid.
"""

import logging
from cadquery.func import spline
from pyknotid.make import trefoil as make_trefoil

from led_knots.core import draw_part, get_config, scale_pyknot_points

logger = logging.getLogger(__name__)

# Load configuration
config = get_config(
    name="Trefoil Knot",
    description="Create and render a trefoil knot"
)

# Generate the trefoil knot path using pyknotid
# This creates a mathematical trefoil knot curve
k = make_trefoil(num_points=50)

# Scale the knot coordinates to fit within the bounding box
# Using width for x, width for y, and height for z (length)
knot_coords = scale_pyknot_points(
    k.points,
    width=config.output_bounds.width,
    height=config.output_bounds.width,
    length=config.output_bounds.height
)

# Convert numpy array to list of 3D points for CadQuery
# pyknotid returns points as (x, y, z) coordinates
knot_points = [(float(p[0]), float(p[1]), float(p[2])) for p in knot_coords]

# Note: Currently when the path is closed, there is an error since faces overlap
# TODO: Fix closed path handling
path = spline(knot_points[:-1])

# Create, sweep, and render the part
draw_part(path, config, rotation_z=90)
